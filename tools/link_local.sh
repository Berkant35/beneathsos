#!/usr/bin/env bash
# Creates git-ignored pubspec_overrides.yaml files so sibling repos resolve from local folders.
# Works with macOS bash 3.2 (no associative arrays).
set -euo pipefail
HUB="$(cd "$(dirname "$0")/.." && pwd)"

deps_for() {
  case "$1" in
    apps/beneathsos_app)     echo "ble_scanner beneathsos_ui rubble_core locator_engine rubble_canvas" ;;
    packages/locator_engine) echo "rubble_core" ;;
    packages/rubble_canvas)  echo "rubble_core" ;;
    *) echo "" ;;
  esac
}

for repo in apps/beneathsos_app packages/locator_engine packages/rubble_canvas; do
  dir="$HUB/$repo"; [ -d "$dir" ] || continue
  out="$dir/pubspec_overrides.yaml"
  echo "# Generated by tools/link_local.sh — local development only, git-ignored." > "$out"
  echo "dependency_overrides:" >> "$out"
  for dep in $(deps_for "$repo"); do
    [ -d "$HUB/packages/$dep" ] || continue
    rel="$(python3 -c 'import os,sys;print(os.path.relpath(sys.argv[1],sys.argv[2]))' "$HUB/packages/$dep" "$dir")"
    printf '  %s:\n    path: %s\n' "$dep" "$rel" >> "$out"
  done
  echo "linked $repo"
done
